#!/usr/bin/env python3
# Regenerates src/appicon.h (the 64x64 RGBA window icon, embedded like Lestrix does) from data/hootedit.png.
# Usage: python3 tools/make_appicon.py   (needs Pillow)
import os
from PIL import Image

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
im = Image.open(os.path.join(root, "data", "hootedit.png")).convert("RGBA").resize((64, 64), Image.LANCZOS)
data = im.tobytes()
lines = []
for i in range(0, len(data), 32):
    lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 32]) + ",")
with open(os.path.join(root, "src", "appicon.h"), "w") as f:
    f.write("/*\n * Copyright (c) 2026 BeanGreen247\n * SPDX-License-Identifier: MIT\n */\n\n")
    f.write("/* generated by tools/make_appicon.py from data/hootedit.png */\n")
    f.write("static const unsigned char APP_ICON_RGBA[64 * 64 * 4] = {\n")
    f.write("\n".join(lines) + "\n};\n")
print("wrote src/appicon.h")
