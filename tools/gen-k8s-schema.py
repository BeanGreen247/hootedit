"""Generate src/k8s_schema.inc (the field tables of the Kubernetes API) from the official OpenAPI v2 spec.

  curl -sLo swagger.json https://raw.githubusercontent.com/kubernetes/kubernetes/master/api/openapi-spec/swagger.json
  tools/gen-k8s-schema.py swagger.json src/k8s_schema.inc [KUBERNETES_VERSION]

Only stable API versions (v1, v2, ...) are included, and descriptions, `status` and managedFields are left out to keep the table small.
A field is a name, a kind (see the enum in src/lint_k8s.cpp), a type reference and a required flag."""
import json, re, sys

F_STR, F_INT, F_NUM, F_BOOL, F_OBJ, F_ARR_OBJ, F_ARR_SCALAR, F_MAP_STR, F_MAP_OBJ, F_ANY, F_INTSTR, F_QUANT, F_MAP_ANY, F_ARR_ANY = range(14)

spec = json.load(open(sys.argv[1]))
out_path = sys.argv[2]
version = sys.argv[3] if len(sys.argv) > 3 else "master"
defs = spec["definitions"]

SCALAR_REFS = {
    "io.k8s.apimachinery.pkg.util.intstr.IntOrString": F_INTSTR,
    "io.k8s.apimachinery.pkg.api.resource.Quantity": F_QUANT,
}
ANY_DEFS = {"io.k8s.apimachinery.pkg.runtime.RawExtension", "io.k8s.apimachinery.pkg.apis.meta.v1.FieldsV1",
            "io.k8s.apiextensions-apiserver.pkg.apis.apiextensions.v1.JSON",
            "io.k8s.apiextensions-apiserver.pkg.apis.apiextensions.v1.JSONSchemaProps"}
SKIP_FIELDS = {"status", "managedFields"}
SKIP_KINDS = {"DeleteOptions", "Status", "WatchEvent", "Patch", "ListOptions", "GetOptions", "CreateOptions", "UpdateOptions", "PatchOptions", "APIGroup",
              "APIVersions", "APIResourceList", "APIGroupList", "TokenReview", "SubjectAccessReview", "SelfSubjectAccessReview", "LocalSubjectAccessReview",
              "SelfSubjectRulesReview", "TokenRequest", "Scale", "Binding", "ComponentStatus"}

type_index = {}   # def name -> index
types = []        # dicts: name, fields, preserve
def ref_name(r): return r.split("/")[-1]

def scalar_kind_of_def(name):
    d = defs[name]
    if name in SCALAR_REFS: return SCALAR_REFS[name]
    if name in ANY_DEFS or d.get("x-kubernetes-preserve-unknown-fields"): return F_ANY
    if "properties" in d: return None
    t = d.get("type")
    if t == "string": return F_STR
    if t == "integer": return F_INT
    if t == "number": return F_NUM
    if t == "boolean": return F_BOOL
    return F_ANY

def need_type(name):
    if name in type_index: return type_index[name]
    idx = len(types); type_index[name] = idx
    types.append({"name": name, "fields": [], "preserve": bool(defs[name].get("x-kubernetes-preserve-unknown-fields"))})
    d = defs[name]; req = set(d.get("required", []))
    fields = []
    for fname, p in sorted(d.get("properties", {}).items()):
        if fname in SKIP_FIELDS:
            fields.append((fname, F_ANY, 0, 0)); continue
        kind, ref = field_kind(p)
        fields.append((fname, kind, ref, 1 if fname in req else 0))
    types[idx]["fields"] = fields
    return idx

def field_kind(p):
    if "$ref" in p:
        n = ref_name(p["$ref"]); k = scalar_kind_of_def(n)
        if k is not None: return k, 0
        return F_OBJ, need_type(n)
    t = p.get("type")
    if t == "string": return F_STR, 0
    if t == "integer": return F_INT, 0
    if t == "number": return F_NUM, 0
    if t == "boolean": return F_BOOL, 0
    if t == "array":
        it = p.get("items", {})
        if "$ref" in it:
            n = ref_name(it["$ref"]); k = scalar_kind_of_def(n)
            if k is None: return F_ARR_OBJ, need_type(n)
            return (F_ARR_SCALAR if k in (F_STR, F_INT, F_NUM, F_BOOL, F_INTSTR, F_QUANT) else F_ARR_ANY), 0
        if it.get("type") in ("string", "integer", "number", "boolean"): return F_ARR_SCALAR, 0
        return F_ARR_ANY, 0
    if t == "object" or "additionalProperties" in p:
        ap = p.get("additionalProperties")
        if isinstance(ap, dict):
            if ap.get("type") == "string": return F_MAP_STR, 0
            if "$ref" in ap:
                n = ref_name(ap["$ref"]); k = scalar_kind_of_def(n)
                if k is None: return F_MAP_OBJ, need_type(n)
                return F_MAP_ANY, 0
            if ap.get("type") == "array": return F_MAP_ANY, 0
        return F_ANY, 0
    return F_ANY, 0

gvks = []
for name, d in sorted(defs.items()):
    for g in d.get("x-kubernetes-group-version-kind", []):
        v, k, grp = g["version"], g["kind"], g["group"]
        if not re.fullmatch(r"v\d+", v) or k.endswith("List") or k in SKIP_KINDS: continue
        gvks.append(((grp + "/" + v) if grp else v, k, name))
gvks = sorted(set(gvks))
roots = [need_type(n) for _, _, n in gvks]

flat = []
for t in types:
    t["first"] = len(flat)
    flat.extend(t["fields"])

def c(s): return json.dumps(s)
with open(out_path, "w") as f:
    f.write("// Generated by tools/gen-k8s-schema.py from the Kubernetes OpenAPI spec (%s). Do not edit.\n" % version)
    f.write("// %d types, %d fields, %d kinds.\n" % (len(types), len(flat), len(gvks)))
    f.write("static const KStaticField KS_FIELDS[] = {\n")
    for (n, k, r, q) in flat: f.write("{%s,%d,%d,%d},\n" % (c(n), k, r, q))
    f.write("};\nstatic const KStaticType KS_TYPES[] = {\n")
    for t in types: f.write("{%s,%d,%d,%d},\n" % (c(t["name"].split(".")[-1]), t["first"], len(t["fields"]), 1 if t["preserve"] else 0))
    f.write("};\nstatic const KStaticGvk KS_GVKS[] = {\n")
    for (gv, k, n), r in zip(gvks, roots): f.write("{%s,%s,%d},\n" % (c(gv), c(k), r))
    f.write("};\n")
print(len(types), "types", len(flat), "fields", len(gvks), "kinds")
